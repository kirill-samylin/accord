#!/usr/bin/env python3
"""Render one IP-bound Accord nginx include; never changes the host or secrets."""
import argparse
import ipaddress


def public_ipv4(value):
    try:
        address = ipaddress.IPv4Address(value)
    except ipaddress.AddressValueError as exc:
        raise argparse.ArgumentTypeError("canonical public IPv4 required") from exc
    if str(address) != value or not address.is_global or address.is_multicast:
        raise argparse.ArgumentTypeError("canonical public unicast IPv4 required")
    return value


def render(address, phase, web=False):
    # Installed inside nginx's http {} context, not as the top-level nginx.conf.
    common = f'''# Generated by render_public.py; only this public interface is bound.
# No raw URI, body, Authorization, identity, or forwarded headers in logs.
limit_req_zone $binary_remote_addr zone=accord_public_rate:1m rate=20r/s;
limit_conn_zone $binary_remote_addr zone=accord_public_connections:1m;
map "$status:$upstream_http_retry_after" $accord_public_retry_after {{
    default "";
    "429:" "1";
}}
map $http_host $accord_http_authority {{
    default 0;
    "{address}" 1;
    "{address}:80" 1;
}}
server {{
    listen {address}:80 default_server;
    server_name {address};
    access_log off;
    error_log /dev/null crit;
    server_tokens off;
    client_max_body_size 64k;
    client_header_timeout 10s;
    client_body_timeout 10s;
    keepalive_timeout 15s;
    limit_req zone=accord_public_rate burst=40 nodelay;
    limit_req_status 429;
    limit_conn accord_public_connections 32;
    limit_conn_status 429;
    add_header Retry-After $accord_public_retry_after always;
    if ($accord_http_authority = 0) {{ return 444; }}
    if ($host != "{address}") {{ return 444; }}
    location ~ ^/\\.well-known/acme-challenge/[A-Za-z0-9_-]+$ {{
        root /var/www/accord-acme;
        default_type text/plain;
        limit_except GET {{ deny all; }}
        try_files $uri =404;
    }}
    # No redirect and no proxy: plaintext bearer requests never reach Accord.
    location / {{ return 404; }}
}}
'''
    if phase == "bootstrap":
        return common
    tls = f'''
map $http_host $accord_https_authority {{
    default 0;
    "{address}" 1;
    "{address}:443" 1;
}}
server {{
    listen {address}:443 ssl default_server;
    server_name {address};
    ssl_certificate /etc/letsencrypt/live/accord-public-ip/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/accord-public-ip/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:accord_public_tls:1m;
    ssl_session_timeout 1h;
    ssl_session_tickets off;
    access_log off;
    error_log /dev/null crit;
    server_tokens off;
    client_max_body_size 64k;
    client_header_buffer_size 1k;
    large_client_header_buffers 2 8k;
    client_header_timeout 10s;
    client_body_timeout 30s;
    keepalive_timeout 30s;
    send_timeout 30s;
    limit_req zone=accord_public_rate burst=40 nodelay;
    limit_req_status 429;
    limit_conn accord_public_connections 32;
    limit_conn_status 429;
    add_header Retry-After $accord_public_retry_after always;
    if ($accord_https_authority = 0) {{ return 444; }}
    if ($host != "{address}") {{ return 444; }}
    # Operational metrics stay available only through the existing private route.
    location = /metrics {{ return 404; }}
    location ~ ^/(api/v1(?:/|$)|mcp$|readyz$|healthz$) {{
        proxy_pass http://127.0.0.1:7892;
        proxy_http_version 1.1;
        proxy_set_header Host 127.0.0.1:7892;
        proxy_set_header Connection "";
        # Preserve Authorization and even an empty Origin exactly as received:
        # nginx's ordinary header pass-through keeps the backend's Origin guard.
        # Do not set Origin $http_origin: that would drop an empty Origin header.
        proxy_set_header Forwarded "";
        proxy_set_header X-Forwarded-For "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header X-Forwarded-Proto "";
        proxy_set_header X-Forwarded-Port "";
        proxy_set_header X-Real-IP "";
        proxy_buffering off;
        proxy_request_buffering off;
        proxy_cache off;
        proxy_max_temp_file_size 0;
        proxy_connect_timeout 3s;
        proxy_send_timeout 30s;
        proxy_read_timeout 3600s;
        proxy_next_upstream off;
        proxy_redirect off;
    }}
    location / {{ return 404; }}
}}
'''
    if web:
        proxy = """        proxy_pass http://127.0.0.1:7892;
        proxy_http_version 1.1;
        proxy_set_header Host 127.0.0.1:7892;
        proxy_set_header Connection "";
        proxy_set_header Forwarded "";
        proxy_set_header X-Forwarded-For "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header X-Forwarded-Proto "";
        proxy_set_header X-Forwarded-Port "";
        proxy_set_header X-Real-IP "";
        # This header is authoritative only on the explicitly trusted loopback link.
        proxy_set_header X-Accord-Client-IP $remote_addr;
        proxy_buffering off;
        proxy_request_buffering off;
        proxy_cache off;
        proxy_max_temp_file_size 0;
        proxy_connect_timeout 3s;
        proxy_send_timeout 120s;
        proxy_read_timeout 120s;
        proxy_next_upstream off;
        proxy_redirect off;
"""
        routes = "    location = / {\n" + proxy + "    }\n"
        routes += "    location /web/ {\n" + proxy + "    }\n"
        routes += "    location = /web/designs {\n        client_max_body_size 52494336;\n        client_body_timeout 120s;\n        send_timeout 120s;\n" + proxy + "    }\n"
        routes += "    location / { return 404; }"
        tls = tls.replace("    location / { return 404; }", routes)
    return common + tls


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ip", required=True, type=public_ipv4)
    parser.add_argument("--phase", choices=("bootstrap", "tls"), required=True)
    parser.add_argument("--web", action="store_true", help="enable reviewed browser and design routes")
    args = parser.parse_args()
    print(render(args.ip, args.phase, args.web), end="")


if __name__ == "__main__":
    main()

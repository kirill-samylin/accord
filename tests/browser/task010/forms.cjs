'use strict';
const h = require('../../process/task010/harness.cjs');
const {assert, origin} = h;
const {settings} = require('../../process/task010/native.cjs');
async function run(f, owner, pass) {
  const p = owner.page;
  await p.getByRole('button', {name: 'Новый профиль', exact: true}).click();
  let dialog = p.getByRole('dialog');
  await dialog.locator('input[name=name]').fill('QA Chrome created');
  await dialog.locator('textarea[name=instructions]').fill('QA Chrome initial instructions');
  await dialog.locator('select[name=provider]').selectOption('custom');
  await dialog.locator('input[name=model]').fill('qa-browser-model');
  const endpoint = '/web/p/' + f.a + '/profiles';
  let captured, committed;
  const matcher = url => url.pathname === endpoint;
  await p.route(matcher, async route => {
    if (route.request().method() !== 'POST' || captured) return route.continue();
    captured = {url: route.request().url(), body: route.request().postData()};
    const actual = await route.fetch(); assert.equal(actual.status(), 200);
    committed = await actual.json(); await route.abort('failed');
  });
  await dialog.getByRole('button', {name: 'Создать профиль', exact: true}).click();
  await dialog.getByText('Результат отправки неизвестен.', {exact: false}).waitFor();
  assert(committed?.redirect, 'intercept must prove the actual server committed');
  const list = await f.owner.read(endpoint); assert.equal(list.data.page.profiles.filter(v => v.name === 'QA Chrome created').length, 1);
  let retry;
  p.on('request', request => {if (request.method() === 'POST' && new URL(request.url()).pathname === endpoint && captured) retry = {url: request.url(), body: request.postData()};});
  await dialog.getByRole('button', {name: 'Повторить ту же отправку', exact: true}).click();
  await p.waitForURL(/\/profiles\/ap_[a-f0-9]{32}$/); await p.getByRole('heading', {name: 'QA Chrome created', exact: true}).waitFor();
  assert.deepEqual(retry, captured, 'retry must freeze exact original body/path/action');
  await p.unroute(matcher);
  f.uiProfile = new URL(p.url()).pathname.split('/').at(-1);
  assert.equal(committed.redirect.split('/').at(-1), f.uiProfile);
  pass('Chrome-actual-committed-lostresponse-exact-profile-create-retry-no-duplicate');
  await p.getByRole('button', {name: 'Изменить', exact: true}).click(); dialog = p.getByRole('dialog');
  await dialog.locator('textarea[name=instructions]').fill('QA Chrome dirty draft kept');
  const page = (await f.owner.read(endpoint + '/' + f.uiProfile)).data.page;
  const changed = await f.owner.post(endpoint + '/' + f.uiProfile + '/update', {csrf: page.csrf, action_id: page.actions['profile:update'], version: '1', ...settings('QA Chrome concurrent', 'QA Chrome concurrent value')});
  assert.equal(changed.status, 200);
  const conflict = p.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/update'));
  await dialog.getByRole('button', {name: 'Сохранить изменения', exact: true}).click(); assert.equal((await conflict).status(), 409);
  await dialog.getByRole('button', {name: 'Применить черновик к версии 2', exact: true}).waitFor();
  assert.equal(await dialog.locator('textarea[name=instructions]').inputValue(), 'QA Chrome dirty draft kept');
  assert(await dialog.getByRole('button', {name: 'Сохранить изменения', exact: true}).isDisabled());
  await dialog.getByRole('button', {name: 'Применить черновик к версии 2', exact: true}).click();
  const saved = p.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/update'));
  await dialog.getByRole('button', {name: 'Сохранить изменения', exact: true}).click(); assert.equal((await saved).status(), 200);
  await dialog.waitFor({state: 'hidden'});
  await p.getByRole('tab', {name: 'Инструкции', exact: true}).click(); assert.match(await p.locator('main').innerText(), /QA Chrome dirty draft kept/);
  await p.getByRole('tab', {name: 'История версий', exact: true}).click();
  await p.getByRole('link', {name: 'Версия 1', exact: true}).click();
  await p.getByText('Открыта сохранённая ревизия 1.', {exact: false}).waitFor();
  assert.equal(await p.getByRole('button', {name: 'Изменить', exact: true}).count(), 0);
  await p.getByRole('tab', {name: 'Инструкции', exact: true}).click(); assert.match(await p.locator('main').innerText(), /QA Chrome initial instructions/);
  await p.getByRole('link', {name: 'Перейти к текущей версии', exact: true}).click();
  await p.getByRole('button', {name: 'В архив', exact: true}).click();
  await p.getByRole('button', {name: 'Восстановить', exact: true}).waitFor();
  assert.match(await p.locator('main').innerText(), /Архивный профиль нельзя выбрать/);
  await p.getByRole('button', {name: 'Восстановить', exact: true}).click();
  await p.getByRole('button', {name: 'В архив', exact: true}).waitFor();
  assert.equal((await f.owner.read(endpoint + '/' + f.uiProfile)).data.page.profile.version, 5);
  pass('Chrome-dirtydraft-concurrent409-explicit-version-rebase-history-archive-restore');
}
module.exports = {run};

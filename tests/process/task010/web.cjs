'use strict';
const h = require('./harness.cjs');
const {assert, BrowserSession} = h;
const {settings} = require('./native.cjs');
const catalog = require('./catalog.cjs');
async function run(f, pass) {
  await f.owner.open(f.a);
  const prefix = '/web/p/' + f.a + '/profiles';
  const page = (await f.owner.read(prefix)).data.page;
  assert(page.can_manage_profiles); assert(page.actions['profile:create']);
  const fields = {csrf: page.csrf, action_id: page.actions['profile:create'], ...settings('QA Web persistent')};
  const invalid = await f.owner.post(prefix, {...fields, name: ''});
  assert.equal(invalid.status, 400); assert(invalid.data.page.actions['profile:create']); assert.notEqual(invalid.data.page.actions['profile:create'], fields.action_id);
  const unknown = await f.owner.post(prefix, {...fields, action_id: invalid.data.page.actions['profile:create'], command: 'forbidden'});
  assert.equal(unknown.status, 400);
  fields.action_id = unknown.data.page.actions['profile:create'];
  const created = await f.owner.post(prefix, fields); assert.equal(created.status, 200, 'corrected create with new capability rejected');
  const replay = await f.owner.post(prefix, fields); assert.equal(replay.status, 200); assert.equal(replay.data.redirect, created.data.redirect);
  const id = created.data.redirect.split('/').at(-1); f.webProfile = id;
  let detail = (await f.owner.read(prefix + '/' + id)).data.page;
  assert.equal(detail.profile.version, 1); assert.equal(detail.profile.instructions, settings().instructions);
  assert.equal((await f.owner.read(prefix + '?state=active&%zz=x')).status, 400);
  assert.equal((await f.owner.read(prefix + '/' + id + '?version=1&extra=x')).status, 400);
  const update = {csrf: detail.csrf, action_id: detail.actions['profile:update'], version: '1', ...settings('QA Web persistent', 'Web instructions two')};
  assert.equal((await f.owner.post(prefix + '/' + id + '/update', update)).status, 200);
  detail = (await f.owner.read(prefix + '/' + id)).data.page;
  const conflict = await f.owner.post(prefix + '/' + id + '/update', {...update, action_id: detail.actions['profile:update']});
  assert.equal(conflict.status, 409); assert.equal(conflict.data.page.profile.version, 2); assert.equal(conflict.data.draft.instructions, 'Web instructions two');
  const history = (await f.owner.read(prefix + '/' + id + '?version=1')).data.page;
  assert.equal(history.profile.version, 1); assert.equal(history.can_manage_profiles, false);
  assert(!history.actions?.['profile:update']);
  pass('browser-JSON-real-CRUD-validation-newcapability-versionconflict-history-and-exact-replay');
  const viewer = await new BrowserSession().login(f.viewer); await viewer.open(f.a);
  const read = await viewer.read(prefix); assert.equal(read.status, 200); assert.equal(read.data.page.can_manage_profiles, false);
  assert(!read.data.page.actions?.['profile:create']);
  assert.equal((await viewer.post(prefix, {...fields, csrf: read.data.page.csrf})).status, 409);
  const editor = await new BrowserSession().login(f.editor); await editor.open(f.a);
  const editPage = (await editor.read(prefix)).data.page;
  const cached = {csrf: editPage.csrf, action_id: editPage.actions['profile:create'], ...settings('QA epoch cached')};
  assert.equal((await editor.post(prefix, cached)).status, 200);
  await catalog.member(f.owner, f.a, f.editor.id, 'viewer', 'set');
  assert.equal((await editor.post(prefix, cached)).status, 403);
  await catalog.member(f.owner, f.a, f.editor.id, 'editor', 'set');
  await catalog.member(f.owner, f.a, f.editor.id, '', 'revoke');
  await catalog.member(f.owner, f.a, f.editor.id, 'editor', 'grant');
  assert([401, 409].includes((await editor.post(prefix, cached)).status));
  pass('browser-viewer-directPOST-and-downgrade-revoke-regrant-cachedaction-denial');
}
module.exports = {run};
